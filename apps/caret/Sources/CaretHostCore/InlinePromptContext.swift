import Foundation

public protocol InlineSecretDetecting {
    func containsSecret(_ text: String) -> Bool
}

public struct NoopInlineSecretDetector: InlineSecretDetecting {
    public init() {}
    public func containsSecret(_ text: String) -> Bool { false }
}

/// Optional context supplied to the on-device inline prompt. The host owns capture and
/// filtering; this value keeps the prompt contract testable without loading the model.
public struct InlinePromptContext: Equatable, Sendable {
    public static let screenTokenBudget = 512
    public static let clipboardTokenBudget = 256
    public static let writingTokenBudget = 256

    public var screenText: String?
    public var previousUserInputs: [String]
    public var pasteboardText: String?

    public init(screenText: String? = nil, previousUserInputs: [String] = [], pasteboardText: String? = nil) {
        self.screenText = screenText
        self.previousUserInputs = previousUserInputs
        self.pasteboardText = pasteboardText
    }

    public var hasPromptContext: Bool {
        screenText != nil || !previousUserInputs.isEmpty || pasteboardText != nil
    }
}

/// Memory-only writing samples. Entries are scoped to the focused app and expire after ten minutes.
public struct InlineWritingMemory: Sendable {
    public struct Entry: Sendable, Equatable {
        public let appBundleIdentifier: String
        public let text: String
        public let recordedAt: Date
        public init(appBundleIdentifier: String, text: String, recordedAt: Date) {
            self.appBundleIdentifier = appBundleIdentifier
            self.text = text
            self.recordedAt = recordedAt
        }
    }

    public static let retention: TimeInterval = 10 * 60
    private var entries: [Entry] = []
    public init() {}

    public mutating func clear() { entries.removeAll() }
    public mutating func record(_ text: String, appBundleIdentifier: String, at now: Date = Date(), secure: Bool, detector: InlineSecretDetecting) {
        prune(at: now)
        guard !secure, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, !detector.containsSecret(text) else { return }
        entries.append(Entry(appBundleIdentifier: appBundleIdentifier, text: text, recordedAt: now))
    }
    public mutating func samples(for appBundleIdentifier: String, at now: Date = Date()) -> [String] {
        prune(at: now)
        return entries.filter { $0.appBundleIdentifier == appBundleIdentifier }.map(\.text)
    }
    private mutating func prune(at now: Date) {
        entries.removeAll { now.timeIntervalSince($0.recordedAt) > Self.retention }
    }
}

public struct InlinePasteboardPolicy: Sendable {
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    public init() {}

    public func acceptedText(enabled: Bool, plainText: String?, types: Set<String>, detector: InlineSecretDetecting, tokenCount: (String) -> Int) -> String? {
        guard enabled, let plainText, !plainText.isEmpty else { return nil }
        guard types.isDisjoint(with: [Self.concealed, Self.transient, Self.autoGenerated]) else { return nil }
        guard tokenCount(plainText) <= InlinePromptContext.clipboardTokenBudget else { return nil }
        guard !detector.containsSecret(plainText) else { return nil }
        return plainText
    }
}
